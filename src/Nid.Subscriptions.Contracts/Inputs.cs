using NodaTime;
using Nid.Core.Contracts;
using Duration = Nid.Core.Contracts.Duration;

namespace Nid.Subscriptions.Contracts;

public enum PayerType
{
    Person,
    Household,
    External,
}

public enum CoverageSource
{
    Paid,
    Bonus,
    Included,
    Trial,
    Gift,
}

public enum PurchaseKind
{
    PrepaidTerm,
    Bundle,
    Gift,
    Adjustment,
    Refund,
}

/// <summary>Who paid. <paramref name="PersonId"/> is set only when <paramref name="Type"/> is Person.</summary>
public sealed record Payer(PayerType Type, PersonId? PersonId);

/// <summary>Coverage granted by a purchase. <paramref name="StartsOn"/> null = stack after the current coverage end.</summary>
public sealed record Grant(ItemId SubscriptionId, Duration Duration, CoverageSource Source, LocalDate? StartsOn);

/// <summary>A recurring pricing rule. It charges when coverage runs out, not on a fixed calendar.</summary>
public sealed record BillingPhase(
    BillingPhaseId Id,
    LocalDate StartsOn,
    LocalDate? EndsOn,
    Money Price,
    Duration Every,
    Duration? Covers,
    int? MaxCycles,
    Payer Payer)
{
    /// <summary>Coverage granted per renewal; defaults to the billing period.</summary>
    public Duration CoverageEvery => Covers ?? Every;
}

/// <summary>A single payment not generated by a phase.</summary>
public sealed record Purchase(
    PurchaseId Id,
    LocalDate Date,
    string Label,
    Money Price,
    Payer Payer,
    PurchaseKind Kind,
    IReadOnlyList<Grant> Grants,
    decimal? AllocatedAmount)
{
    /// <summary>What counts as subscription cost: the allocated part for bundles, the whole price otherwise.</summary>
    public decimal CostBasis => AllocatedAmount ?? (Kind == PurchaseKind.Bundle ? 0m : Price.Amount);
}

/// <summary>What the engine needs of a subscription. Name, provider and users belong to 1C, not here.</summary>
public sealed record SubscriptionHeader(ItemId Id, bool AutoRenew, LocalDate? CancelledAt);

public sealed record SubscriptionInput(
    SubscriptionHeader Subscription,
    IReadOnlyList<BillingPhase> Phases,
    IReadOnlyList<Purchase> Purchases);
