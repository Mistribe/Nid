using NodaTime;

namespace Nid.Documents.Infrastructure.Persistence;

public sealed class DocumentRow
{
    public Guid Id { get; set; }
    public string Sha256 { get; set; } = "";
    public long SizeBytes { get; set; }
    public string MediaType { get; set; } = "";
    public string OriginalFilename { get; set; } = "";
    public string Title { get; set; } = "";
    public LocalDate? DocumentDate { get; set; }
    public string? Note { get; set; }
    public Guid UploadedByPersonId { get; set; }
    public Instant UploadedAt { get; set; }
    public Instant? ArchivedAt { get; set; }
    public string? SourceRef { get; set; }

    /// <summary>#506: the row's <c>xmin</c>, the version an edit or an archive must name.</summary>
    public uint Version { get; set; }
}

public sealed class DocumentLinkRow
{
    public Guid DocumentId { get; set; }
    public string TargetKind { get; set; } = "";
    public Guid TargetId { get; set; }
    public Guid? AnchorItemId { get; set; }
    public string Role { get; set; } = "";
    public Guid LinkedByPersonId { get; set; }
    public Instant LinkedAt { get; set; }
}

/// <summary>Issue #414: a document marked « pas disponible »: that period of that role on that target is no longer asked for.</summary>
public sealed class ExpectedDismissalRow
{
    public string TargetKind { get; set; } = "";
    public Guid TargetId { get; set; }
    public string Role { get; set; } = "";
    public int Period { get; set; }
    public Guid DismissedByPersonId { get; set; }
    public Instant DismissedAt { get; set; }
}

/// <summary>#305: an upload URL not used yet; no history, it is deleted when claimed or expired.</summary>
public sealed class UploadTicketRow
{
    public string TokenHash { get; set; } = "";
    public Guid PersonId { get; set; }
    public Guid TokenId { get; set; }
    public string FileName { get; set; } = "";
    public string Title { get; set; } = "";
    public LocalDate DocumentDate { get; set; }
    public string? Note { get; set; }
    public string TargetKind { get; set; } = "";
    public Guid TargetId { get; set; }
    public string Role { get; set; } = "";
    public string? SourceRef { get; set; }
    public Instant ExpiresAt { get; set; }
}

/// <summary>#167: one page of a document's text, as a worker read it; derived from the file, so not audited. Deleted with its
/// document.</summary>
public sealed class DocumentTextRow
{
    public Guid DocumentId { get; set; }
    public int Page { get; set; }
    public string Text { get; set; } = "";
    public string Source { get; set; } = "";
    public Instant ExtractedAt { get; set; }
}

/// <summary>#167: the job that asked for a document's text; the backfill asks only for documents without one.</summary>
public sealed class DocumentTextJobRow
{
    public Guid DocumentId { get; set; }
    public Guid JobId { get; set; }
    public Instant QueuedAt { get; set; }
}

/// <summary>#559: one chunk of a document's text (<see cref="Nid.Documents.Domain.Chunks"/>), with its French full-text vector,
/// generated by Postgres. Its embeddings are in <c>documents.chunk_embedding</c>, written in SQL (pgvector's type). Derived
/// from the text, so not audited; deleted with its document.</summary>
public sealed class DocumentChunkRow
{
    public Guid Id { get; set; }
    public Guid DocumentId { get; set; }
    public int Ordinal { get; set; }
    public int Page { get; set; }
    public string Text { get; set; } = "";
    public NpgsqlTypes.NpgsqlTsVector Search { get; set; } = null!;
}
